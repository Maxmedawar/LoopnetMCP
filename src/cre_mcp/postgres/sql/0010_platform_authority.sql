-- Phase 6A: the hosted platform authority tables.
--
-- This is a faithful PostgreSQL port of the SQLite ``platform_*`` schema that
-- lives under ``src/cre_mcp/platform/``. It exists so the hosted process can
-- boot on PostgreSQL without carrying a second, divergent definition of who a
-- user is, which workspace they belong to, which OAuth session speaks for
-- them, and which provider receipt granted them access. Every table, index,
-- constraint and trigger below was captured by building the SQLite schema in
-- an in-memory database (schema.SCHEMA + platform-core + admin-controls +
-- oauth + entitlements + provider-sync migrations, plus the connection.py
-- tables) and dumping ``sqlite_master``, so the f-string-interpolated CHECK
-- choice lists are the resolved literals rather than a hand transcription.
--
-- Type mapping: INTEGER -> bigint, REAL -> double precision, TEXT -> text.
-- ``INTEGER PRIMARY KEY AUTOINCREMENT`` becomes
-- ``bigint GENERATED BY DEFAULT AS IDENTITY`` — BY DEFAULT, not ALWAYS, so an
-- explicit id can still be supplied exactly as SQLite allows. Columns that
-- hold 0/1 flags stay numeric ``bigint`` with their ``CHECK(x IN (0,1))``:
-- the Python stores write and compare integers, and turning them into
-- ``boolean`` would silently change every comparison in the store code.
--
-- NO ROW-LEVEL SECURITY ON ANY TABLE BELOW — deliberately.
-- These stores are the identity and authority layer. They run BEFORE a
-- workspace context exists: resolving a browser session to a user, exchanging
-- an authorization code, deciding which workspace a provider receipt even
-- belongs to. There is no ``app.workspace_id`` to filter on at that point, so
-- an RLS policy here would either be a no-op or would lock the authority layer
-- out of its own bootstrap. Tenancy on these tables is enforced in the store
-- code exactly as it was under SQLite, and the grant boundary below is the
-- database-side control. The certified ``medawarcre.*`` tenant tables from
-- migrations 0001-0009 keep their RLS unchanged; nothing here touches them.

