       AND (NEW.source <> 'jv' OR NEW.subject_user_id IS NOT NULL) THEN
        RAISE EXCEPTION 'workspace scope requires subjectless jv grant'
            USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.scope = 'subject' AND NEW.subject_user_id IS NULL THEN
        RAISE EXCEPTION 'subject scope requires subject'
            USING ERRCODE = 'check_violation';
    END IF;
