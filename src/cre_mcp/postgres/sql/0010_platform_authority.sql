-- src/cre_mcp/platform/entitlements.py:1262 and :1271 — grant scope binding.
-- This carries real security semantics: it is what stops a provider grant from
-- being written without a subject, and what stops a subject grant from naming
-- a user who is not a member of the workspace it grants access to. The SQLite
-- form is a chain of SELECT CASE WHEN ... THEN RAISE(ABORT, ...) END; each one
-- becomes an IF ... THEN RAISE EXCEPTION ... END IF in the same order.
CREATE FUNCTION medawarcre.platform_grant_scope_binding()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $function$
BEGIN
    IF NEW.scope IS NULL
       OR NEW.scope NOT IN ('subject','workspace') THEN
        RAISE EXCEPTION 'grant scope is invalid'
            USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.source IN ('stripe','skool','manual','promotion')
       AND (NEW.scope IS NULL OR NEW.scope <> 'subject') THEN
        RAISE EXCEPTION 'grant source requires subject scope'
            USING ERRCODE = 'check_violation';
